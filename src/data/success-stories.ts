/** Distinct industries across the library, for the picker's filter row. */
export const SUCCESS_STORY_INDUSTRIES: string[] = [
  ...new Set(SUCCESS_STORIES.map((s) => s.industry)),
].sort();

/** Free-text search across name, anonName, industry, geo, subtitle, chapter. */
export function searchSuccessStories(query: string): SuccessStory[] {
  const q = query.trim().toLowerCase();
  if (!q) return SUCCESS_STORIES;
  return SUCCESS_STORIES.filter((s) =>
    [s.name, s.anonName, s.industry, s.geo, s.subtitle, s.chapter]
      .join(" ")
      .toLowerCase()
      .includes(q),
  );
}

/** Narrow the library to a single industry (null = all). */
export function filterStoriesByIndustry(industry: string | null): SuccessStory[] {
  if (!industry) return SUCCESS_STORIES;
  return SUCCESS_STORIES.filter((s) => s.industry === industry);
}

/** Look up a single story by id. */
export function getSuccessStory(id: string): SuccessStory | undefined {
  return SUCCESS_STORIES.find((s) => s.id === id);
}

/** Convert a story to the chapter-card shape, honouring the anon toggle. */
export function toCaseStudy(
  story: SuccessStory,
  opts?: { anon?: boolean },
): ChapterCaseStudy {
  return {
    name: opts?.anon ? story.anonName : story.name,
    subtitle: story.subtitle,
    before: story.before,
    after: story.after,
    metrics: story.metrics,
  };
}
